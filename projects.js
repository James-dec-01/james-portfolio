(function () {
  'use strict';

  var section = document.getElementById('work');
  if (!section) return;

  var data = window.PORTFOLIO_PROJECTS || [];
  var stage = section.querySelector('[data-fan-stage]');
  var fan = section.querySelector('[data-fan]');
  var cards = Array.prototype.slice.call(section.querySelectorAll('.prj-card'));
  var modal = document.getElementById('project-modal');
  var mKicker = document.getElementById('prj-modal-kicker');
  var mTitle = document.getElementById('prj-modal-title');
  var mMeta = document.getElementById('prj-modal-meta');
  var mPages = document.getElementById('prj-modal-pages');
  var mClose = modal ? modal.querySelector('.prj-modal__close') : null;

  var reducedMotion = window.matchMedia
    ? window.matchMedia('(prefers-reduced-motion: reduce)')
    : null;
  var narrow = window.matchMedia ? window.matchMedia('(max-width: 760px)') : null;
  var fineMq = window.matchMedia ? window.matchMedia('(hover: hover) and (pointer: fine)') : null;

  var hotCard = null;
  var leaveTimer = 0;
  var activeMobile = 3;
  var openToken = 0;
  var lastTrigger = null;
  var closeTimer = 0;
  var scrollLock = null;
  var suppressClick = false;
  var suppressTimer = 0;
  var dragStart = null;

  function isReduced() {
    return !!(reducedMotion && reducedMotion.matches);
  }

  function isNarrow() {
    return !!(narrow && narrow.matches);
  }

  /* ---------- card group: vertical deck on entry, then a single
     automatic fan reveal (stack 0.4s, fan ~0.9s => 1.5s total).
     No scroll scrubbing and no mouse-driven group expansion. ---------- */

  var STACK_HOLD = 380;
  var revealTimer = 0;
  var revealed = false;
  var entered = false;

  function revealNow() {
    if (!fan || revealed) return;
    revealed = true;
    fan.classList.remove('is-idle');
    fan.classList.add('is-open');
  }

  function armStack() {
    if (!fan) return;
    window.clearTimeout(revealTimer);
    if (isReduced()) {
      revealed = true;
      fan.classList.remove('is-idle');
      fan.classList.add('is-open');
      return;
    }
    if (revealed) return;
    fan.classList.remove('is-open');
    fan.classList.add('is-idle');
  }

  var entryObserver = null;

  function observeEntry() {
    if (!stage || !fan) return;
    if (entryObserver) {
      entryObserver.disconnect();
      entryObserver = null;
    }
    if (isReduced() || !('IntersectionObserver' in window)) {
      if (isReduced()) revealNow();
      else {
        revealed = true;
        fan.classList.add('is-open');
      }
      return;
    }
    entryObserver = new IntersectionObserver(function (entries) {
      for (var i = 0; i < entries.length; i++) {
        if (!entries[i].isIntersecting) continue;
        entryObserver.disconnect();
        entryObserver = null;
        if (entered || revealed) return;
        entered = true;
        revealTimer = window.setTimeout(revealNow, STACK_HOLD);
        return;
      }
    }, { threshold: 0.12 });
    entryObserver.observe(stage);
  }

  /* fit the fan to the stage: the larger card size and the unequal
     wave offsets must still stay inside the viewport at every width.
     4.103 is the full horizontal extent of the fan in card-width
     units (outer centre 1.595 + rotated bbox 0.4565); 14px total side
     padding keeps the outer corners off the viewport edge. */
  function fitCards() {
    if (!stage || !section) return;
    if (isNarrow()) {
      section.style.removeProperty('--cw');
      return;
    }
    var w = stage.clientWidth || section.clientWidth || 0;
    if (!w) return;
    var cw = Math.min(408, Math.max(196, (w - 8) / 3.856));
    section.style.setProperty('--cw', cw.toFixed(2) + 'px');
  }

  /* ---------- idle float: inner layer, never fights reading ----------
     Every card gets its own pair of cycles, so the wave never looks
     like a single synchronised animation: vertical travel of roughly
     +/-6-10px plus a 3-5deg rotateX / rotateY lean. The hovered card
     (and the mobile active card) settles to a tiny residual so the
     caption stays stable. Suppressed while the deck is still stacked
     and under reduced motion. */

  var FLOAT = [
    { py: 8.4, px: 11.3, pz: 9.7, ay: 7.4, rx: 4.6, ry: 5.2, ph: 0.0 },
    { py: 9.2, px: 12.8, pz: 10.6, ay: 5.8, rx: 5.8, ry: 4.3, ph: 1.37 },
    { py: 7.4, px: 10.4, pz: 12.2, ay: 6.9, rx: 4.2, ry: 5.6, ph: 2.71 },
    { py: 9.8, px: 13.6, pz: 9.2, ay: 5.4, rx: 5.9, ry: 4.4, ph: 4.11 },
    { py: 8.1, px: 11.9, pz: 10.1, ay: 7.8, rx: 4.4, ry: 5.0, ph: 5.53 },
    { py: 8.8, px: 12.4, pz: 11.7, ay: 5.5, rx: 5.5, ry: 4.2, ph: 0.77 },
    { py: 7.7, px: 10.9, pz: 12.8, ay: 7.1, rx: 4.8, ry: 5.8, ph: 2.13 }
  ];
  var floatLayers = [];
  var floatEase = [];
  var floatRaf = 0;
  var floatStart = 0;

  /* ---------- hover / focus ---------- */

  function clearHot() {
    if (hotCard) hotCard.classList.remove('is-hot');
    hotCard = null;
    window.clearTimeout(leaveTimer);
  }

  function setHot(card) {
    if (hotCard === card) return;
    window.clearTimeout(leaveTimer);
    if (hotCard) hotCard.classList.remove('is-hot');
    hotCard = card;
    card.classList.add('is-hot');
  }

  function releaseHot(card) {
    window.clearTimeout(leaveTimer);
    leaveTimer = window.setTimeout(function () {
      if (hotCard !== card) return;
      var hovered = false;
      try {
        hovered = card.matches(':hover');
      } catch (error) {
        hovered = false;
      }
      if (!hovered && !card.contains(document.activeElement)) clearHot();
    }, 40);
  }

  /* ---------- idle float: inner layer, never fights reading ---------- */

  function buildFloat() {
    floatLayers = cards.map(function (card) {
      return card.querySelector('.prj-card__float');
    });
    /* start at rest so the vertical deck stays calm, then ease the
       wave in once the group has opened */
    floatEase = cards.map(function () { return 0; });
  }

  function floatFrame(now) {
    floatRaf = window.requestAnimationFrame(floatFrame);
    if (document.hidden || isReduced()) return;
    if (!floatStart) floatStart = now;
    var t = (now - floatStart) / 1000;
    var fanned = !!(fan && !fan.classList.contains('is-idle'));
    var scale = isNarrow() ? 0.58 : 1;
    for (var i = 0; i < floatLayers.length; i++) {
      var layer = floatLayers[i];
      if (!layer) continue;
      var conf = FLOAT[i] || FLOAT[0];
      var settled = cards[i] === hotCard || (isNarrow() && cards[i].classList.contains('is-current'));
      var target = settled ? 0.08 : (fanned ? 1 : 0);
      floatEase[i] += (target - floatEase[i]) * 0.06;
      var e = floatEase[i] * scale;
      var y = Math.sin((t * Math.PI * 2) / conf.py + conf.ph) * conf.ay * e;
      var rx = Math.sin((t * Math.PI * 2) / conf.px + conf.ph * 1.7 + 0.8) * conf.rx * e;
      var ry = Math.cos((t * Math.PI * 2) / conf.pz + conf.ph * 0.9 + 0.3) * conf.ry * e;
      layer.style.transform =
        'perspective(1100px) translate3d(0,' + y.toFixed(2) + 'px,0)' +
        ' rotateX(' + rx.toFixed(2) + 'deg)' +
        ' rotateY(' + ry.toFixed(2) + 'deg)';
    }
  }

  function startFloat() {
    if (floatRaf) return;
    floatRaf = window.requestAnimationFrame(floatFrame);
  }

  function stopFloat() {
    if (floatRaf) window.cancelAnimationFrame(floatRaf);
    floatRaf = 0;
    for (var i = 0; i < floatLayers.length; i++) {
      if (floatLayers[i]) floatLayers[i].style.transform = 'translate3d(0,0,0)';
    }
  }

  /* ---------- mobile active card ---------- */

  function setActive(index) {
    var count = cards.length;
    if (!count) return;
    if (!isNarrow()) {
      cards.forEach(function (card) { card.classList.remove('is-current'); });
      return;
    }
    activeMobile = (index + count) % count;
    cards.forEach(function (card, i) {
      card.classList.toggle('is-current', i === activeMobile);
    });
  }

  /* ---------- card wiring ---------- */

  cards.forEach(function (card, i) {
    var button = card.querySelector('.prj-card__btn');
    var project = data[i];
    if (!button) return;

    button.addEventListener('pointerenter', function (event) {
      if (event.pointerType && event.pointerType !== 'mouse') return;
      setHot(card);
    });

    button.addEventListener('pointerleave', function (event) {
      if (event.pointerType && event.pointerType !== 'mouse') return;
      button.style.removeProperty('--btx');
      button.style.removeProperty('--bty');
      releaseHot(card);
    });

    button.addEventListener('pointermove', function (event) {
      if (!fineMq || !fineMq.matches || isReduced()) return;
      if (event.pointerType && event.pointerType !== 'mouse') return;
      if (modal && !modal.hidden) return;
      var rect = button.getBoundingClientRect();
      if (!rect.width || !rect.height) return;
      var nx = ((event.clientX - rect.left) / rect.width) * 2 - 1;
      var ny = ((event.clientY - rect.top) / rect.height) * 2 - 1;
      nx = Math.max(-1, Math.min(1, nx));
      ny = Math.max(-1, Math.min(1, ny));
      button.style.setProperty('--bty', (nx * 5).toFixed(2) + 'deg');
      button.style.setProperty('--btx', (-ny * 4).toFixed(2) + 'deg');
    }, { passive: true });

    button.addEventListener('focus', function () {
      if (isNarrow()) setActive(i);
      setHot(card);
    });

    button.addEventListener('blur', function () {
      button.style.removeProperty('--btx');
      button.style.removeProperty('--bty');
      releaseHot(card);
    });

    button.addEventListener('click', function () {
      if (suppressClick) return;
      if (!project) return;
      openProject(project, button);
    });
  });

  /* swipe horizontally to bring another card forward (touch only,
     vertical scrolling is never blocked) */
  if (stage) {
    stage.addEventListener('pointerdown', function (event) {
      if (event.pointerType === 'mouse') return;
      dragStart = { x: event.clientX, y: event.clientY };
    }, { passive: true });
  }

  window.addEventListener('pointerup', function (event) {
    if (!dragStart) return;
    var dx = event.clientX - dragStart.x;
    var dy = event.clientY - dragStart.y;
    dragStart = null;
    if (!isNarrow()) return;
    if (Math.abs(dx) < 30 || Math.abs(dx) < Math.abs(dy) * 1.15) return;
    setActive(activeMobile + (dx < 0 ? 1 : -1));
    suppressClick = true;
    window.clearTimeout(suppressTimer);
    suppressTimer = window.setTimeout(function () {
      suppressClick = false;
    }, 260);
  }, { passive: true });

  window.addEventListener('pointercancel', function () {
    dragStart = null;
  }, { passive: true });

  /* ---------- modal ---------- */

  var manifestPromise = null;

  function loadManifest() {
    if (manifestPromise) return manifestPromise;
    if (typeof fetch !== 'function') {
      manifestPromise = Promise.resolve(null);
      return manifestPromise;
    }
    manifestPromise = fetch('project-assets/manifest.json', { cache: 'no-cache' })
      .then(function (response) {
        if (!response.ok) throw new Error('manifest unavailable');
        return response.json();
      })
      .then(function (json) {
        return json && json.projects ? json.projects : null;
      })
      .catch(function () {
        return null;
      });
    return manifestPromise;
  }

  function probePages(project) {
    var found = [];
    var max = 30;

    function test(url) {
      return new Promise(function (resolve) {
        var probe = new Image();
        probe.onload = function () { resolve(true); };
        probe.onerror = function () { resolve(false); };
        probe.src = url;
      });
    }

    function next(page) {
      if (page > max) return Promise.resolve(found);
      var url = 'project-assets/' + project.slug + '-' + (page < 10 ? '0' + page : page) + '.webp';
      return test(url).then(function (ok) {
        if (!ok) return found;
        found.push(url);
        return next(page + 1);
      });
    }

    return next(1);
  }

  function planPageUrls(project) {
    if (Array.isArray(project.longImages) && project.longImages.length) {
      return Promise.resolve(project.longImages.slice());
    }
    return loadManifest().then(function (projects) {
      var list = projects && projects[project.slug];
      if (Array.isArray(list) && list.length) return list.slice();
      return probePages(project);
    });
  }

  function pageFigure(project, url, index) {
    var figure = document.createElement('figure');
    figure.className = 'prj-page';

    var skeleton = document.createElement('span');
    skeleton.className = 'prj-page__skeleton';
    skeleton.setAttribute('aria-hidden', 'true');

    var image = document.createElement('img');
    image.className = 'prj-page__img';
    image.alt = project.company + ' · ' + project.title + ' 项目长图 ' + (index + 1);
    image.decoding = 'async';
    image.loading = 'eager';

    image.addEventListener('load', function () {
      figure.classList.add('is-loaded');
    });
    image.addEventListener('error', function () {
      figure.classList.add('is-error');
    });

    var error = document.createElement('p');
    error.className = 'prj-page__error';
    error.appendChild(document.createTextNode('第 ' + (index + 1) + ' 张长图加载失败：'));
    var code = document.createElement('code');
    code.textContent = url;
    error.appendChild(code);

    image.src = url;
    figure.appendChild(skeleton);
    figure.appendChild(image);
    figure.appendChild(error);
    return figure;
  }

  function renderLoading() {
    if (!mPages) return;
    mPages.textContent = '';
    var figure = document.createElement('figure');
    figure.className = 'prj-page';
    var skeleton = document.createElement('span');
    skeleton.className = 'prj-page__skeleton';
    skeleton.style.minHeight = '46vh';
    skeleton.setAttribute('aria-hidden', 'true');
    figure.appendChild(skeleton);
    mPages.appendChild(figure);
  }

  function renderEmpty() {
    if (!mPages) return;
    mPages.textContent = '';
    var box = document.createElement('div');
    box.className = 'prj-empty';
    var title = document.createElement('strong');
    title.textContent = '项目长图整理中';
    var copy = document.createElement('p');
    copy.textContent = '该项目长图正在整理，接入后会自动按原始比例完整展示，不做裁切。';
    box.appendChild(title);
    box.appendChild(copy);
    mPages.appendChild(box);
  }

  function renderPages(project, urls) {
    if (!mPages) return;
    if (!urls.length) {
      renderEmpty();
      return;
    }
    mPages.textContent = '';
    urls.forEach(function (url, index) {
      mPages.appendChild(pageFigure(project, url, index));
    });
  }

  function lockScroll() {
    if (scrollLock) return;
    var body = document.body;
    var gap = window.innerWidth - document.documentElement.clientWidth;
    scrollLock = { overflow: body.style.overflow, paddingRight: body.style.paddingRight };
    body.style.overflow = 'hidden';
    if (gap > 0) {
      var current = parseFloat(window.getComputedStyle(body).paddingRight) || 0;
      body.style.paddingRight = (current + gap) + 'px';
    }
  }

  function unlockScroll() {
    if (!scrollLock) return;
    document.body.style.overflow = scrollLock.overflow;
    document.body.style.paddingRight = scrollLock.paddingRight;
    scrollLock = null;
  }

  function focusables() {
    if (!modal) return [];
    return Array.prototype.slice.call(modal.querySelectorAll('button, [href], [tabindex]:not([tabindex="-1"])'))
      .filter(function (el) { return !el.hidden && el.getClientRects().length > 0; });
  }

  function openProject(project, trigger) {
    if (!modal) return;
    window.clearTimeout(closeTimer);
    lastTrigger = trigger || document.activeElement;
    openToken += 1;
    var token = openToken;

    if (mKicker) mKicker.textContent = project.index + ' / ' + project.company + ' — 项目长图';
    if (mTitle) mTitle.textContent = project.title;
    if (mMeta) mMeta.textContent = project.meta || '';

    renderLoading();
    clearHot();
    lockScroll();
    modal.hidden = false;
    var scroll = modal.querySelector('.prj-modal__scroll');
    if (scroll) scroll.scrollTop = 0;
    void modal.offsetWidth;
    modal.classList.add('is-open');

    window.setTimeout(function () {
      if (token === openToken && !modal.hidden) {
        if (mClose) mClose.focus({ preventScroll: true });
      }
    }, 40);

    planPageUrls(project).then(function (urls) {
      if (token !== openToken || modal.hidden) return;
      renderPages(project, urls);
    });
  }

  function closeProject() {
    if (!modal || modal.hidden || !modal.classList.contains('is-open')) return;
    openToken += 1;
    modal.classList.remove('is-open');
    unlockScroll();
    window.clearTimeout(closeTimer);
    closeTimer = window.setTimeout(function () {
      modal.hidden = true;
      var target = lastTrigger;
      lastTrigger = null;
      if (target && document.contains(target)) {
        try { target.focus({ preventScroll: true }); } catch (error) { target.focus(); }
      }
    }, isReduced() ? 0 : 240);
  }

  if (modal) {
    modal.addEventListener('click', function (event) {
      var target = event.target;
      if (target && target.nodeType === 1 && target.hasAttribute('data-modal-close')) {
        closeProject();
      }
    });

    modal.addEventListener('keydown', function (event) {
      if (event.key === 'Escape') {
        event.preventDefault();
        closeProject();
        return;
      }
      if (event.key !== 'Tab') return;
      var list = focusables();
      if (!list.length) return;
      var first = list[0];
      var last = list[list.length - 1];
      if (event.shiftKey && document.activeElement === first) {
        event.preventDefault();
        last.focus();
      } else if (!event.shiftKey && document.activeElement === last) {
        event.preventDefault();
        first.focus();
      }
    });
  }

  document.addEventListener('keydown', function (event) {
    if (event.key === 'Escape' && modal && !modal.hidden) {
      event.preventDefault();
      closeProject();
    }
  });

  /* ---------- viewport changes ---------- */

  function onNarrowChange() {
    clearHot();
    fitCards();
    if (isNarrow()) {
      setActive(activeMobile);
    } else {
      cards.forEach(function (card) { card.classList.remove('is-current'); });
    }
  }

  if (narrow && narrow.addEventListener) {
    narrow.addEventListener('change', onNarrowChange);
  }

  if (reducedMotion && reducedMotion.addEventListener) {
    reducedMotion.addEventListener('change', function () {
      if (reducedMotion.matches) {
        clearHot();
        stopFloat();
        window.clearTimeout(revealTimer);
        revealed = true;
        fan.classList.remove('is-idle');
        fan.classList.add('is-open');
      } else {
        floatStart = 0;
        startFloat();
        if (!revealed) {
          fan.classList.remove('is-open');
          fan.classList.add('is-idle');
        }
      }
    });
  }

  fitCards();
  buildFloat();
  setActive(activeMobile);
  armStack();
  observeEntry();

  if (document.fonts && document.fonts.ready) {
    document.fonts.ready.then(function () {
      fitCards();
    });
  }

  if (isReduced()) {
    stopFloat();
  } else {
    startFloat();
  }

  var layoutRaf = 0;

  function relayout() {
    if (layoutRaf) return;
    layoutRaf = window.requestAnimationFrame(function () {
      layoutRaf = 0;
      fitCards();
    });
  }

  window.addEventListener('resize', relayout, { passive: true });
  window.addEventListener('orientationchange', relayout, { passive: true });
})();
